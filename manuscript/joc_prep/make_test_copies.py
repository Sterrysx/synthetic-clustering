"""Create the test copies in joc_prep/test/ from ../main.tex and
../supplementary.tex.  The originals are only read, never written."""
import re, pathlib
J = pathlib.Path(__file__).resolve().parent
M = J.parent
T = J / 'test'; T.mkdir(exist_ok=True)
main = (M / 'main.tex').read_text()
supp = (M / 'supplementary.tex').read_text()

DC = r'\documentclass[pdflatex,sn-basic]{sn-jnl}'
assert main.count(DC) == 1 and supp.count(DC) == 1

def sub1(s, old, new):
    assert s.count(old) == 1, (old[:60], s.count(old))
    return s.replace(old, new)

def drop_appendices(s):
    a = s.index(r'\begin{appendices}'); b = s.index(r'\end{appendices}') + len(r'\end{appendices}')
    s = s[:a] + '% [joc_prep test copy] Appendices A and B moved to the supplementary material.\n' + s[b:]
    # keep the two cross-references resolvable in the test copy
    s = sub1(s, r'Appendix~\ref{app:algorithms}', r'Supplementary Material, Appendix~A')
    s = sub1(s, r'(Appendix~\ref{app:complexity})', r'(Supplementary Material, Appendix~B)')
    return s

HDR = '% [joc_prep test copy generated by make_test_copies.py from ../main.tex -- do not edit]\n'

# A. bibliography test: original sn-jnl layout, JoC reference style
a = sub1(main, DC, r'\documentclass[pdflatex]{sn-jnl}' + '\n' + r'\input{joc_bib}')
(T / 'main_bibtest.tex').write_text(HDR + a)

# B. referee layout, full v4 copy
b = sub1(main, DC, r'\documentclass[pdflatex,referee]{sn-jnl}' + '\n'
         r'\input{joc_referee}' + '\n' r'\input{joc_bib}')
(T / 'main_referee_full.tex').write_text(HDR + b)

# C. referee layout, appendices removed
c = drop_appendices(b)
(T / 'main_referee_noapp.tex').write_text(HDR + c)

# D. blind submission copy = C + blind switch
d = sub1(c, r'\input{joc_bib}', r'\input{joc_bib}' + '\n' + r'\input{blind}')
d = sub1(d, r'\url{https://github.com/Sterrysx/synthetic-clustering}', r'\repourl')
d = sub1(d, r'''As a concrete next step, we propose applying the framework to the wearable
dataset described in \citet{vidiella2025}, to which we have direct access.''',
r'''As a concrete next step, we propose applying the framework to the wearable
dataset described in \citet{vidiella2025}\blindhide{, to which we have direct access}.''')
# Declarations: keep the section, hide identifying statements in blind mode
decl_a = d.index(r'\noindent \textbf{Funding:}')
decl_b = d.index(r'\bibliography{refs}')
decl = d[decl_a:decl_b]
d = d[:decl_a] + (r'\ifblind' + '\n'
    r'\noindent Funding, competing interests and author contributions are given on' + '\n'
    r'the separate title page (removed for anonymous review).' + '\n\n'
    r'\noindent \textbf{Data availability:} All data analysed in this study are' + '\n'
    r'  simulated; they can be regenerated exactly from the configuration file and' + '\n'
    r'  seeds distributed with the code.' + '\n\n'
    r'\noindent \textbf{Code availability:} The full pipeline is available at' + '\n'
    r'  \repourl\ (anonymised for review).' + '\n\n'
    r'\else' + '\n' + decl + r'\fi' + '\n\n') + d[decl_b:]
(T / 'main_blind.tex').write_text(HDR + d)

# E. blinded supplementary copy (referee layout + blind header)
hdr = (J / 'supplementary_header_blind.tex').read_text()
s_a = supp.index(DC); s_b = supp.index(r'\maketitle') + len(r'\maketitle')
e = HDR + hdr + supp[s_b:]
(T / 'supplementary_blind.tex').write_text(e)
print('written:', sorted(p.name for p in T.glob('*.tex')))
